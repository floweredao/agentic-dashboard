test(`numbers before a unit are written as they are read (${CASES.length} cases)`, () => {
  for (const [input, spoken] of CASES) expect(`${input} => ${spokenNumbers(input)}`).toBe(`${input} => ${spoken}`);
});

test("한자어 and 고유어 numbers", () => {
  expect([0, 1, 10, 11, 20, 105, 2026, 10000, 29000, 100000000].map(sinoNumber))
    .toEqual(["영", "일", "십", "십일", "이십", "백오", "이천이십육", "만", "이만 구천", "일억"]);
  expect([1, 2, 3, 4, 10, 20, 21, 30, 99, 100, 0].map(nativeNumber))
    .toEqual(["한", "두", "세", "네", "열", "스무", "스물한", "서른", "아흔아홉", null, null]);
});

test("the figures a summary states, as digits with their unit or as read; single bare digits and model names are not figures", () => {
  expect(statedFigures("G7이 2만9000개, 5곳, 9월 28일 기준 5분의 1을 2026 RE에서 밝혔다.")).toEqual([
    { raw: "2만9000개", forms: ["2만9000개", "이만구천개"] },
    { raw: "5곳", forms: ["5곳", "다섯곳"] },
    { raw: "9월", forms: ["9월", "구월"] },
    { raw: "28일", forms: ["28일", "이십팔일"] },
    { raw: "5분", forms: ["5분", "오분"] },
    { raw: "2026", forms: ["2026"] },
  ]);
});
